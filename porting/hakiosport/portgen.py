"""Device-port generation and validation.

Generation is idempotent and non-destructive: a file that exists and was changed
by a person is never overwritten.  A manifest of hashes distinguishes "we wrote
this and it is unchanged" from "somebody edited this".
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from . import __version__
from .devices import DeviceSpec

MANIFEST = ".port-manifest.json"


@dataclass
class PortResult:
    port: Path
    created: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    skipped_modified: list[str] = field(default_factory=list)
    issues: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.issues


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_path(path: Path) -> str:
    return sha256_bytes(Path(path).read_bytes())


def _board_dts(spec: DeviceSpec) -> str:
    description = spec.display_name.replace('"', "'")
    return f'''/dts-v1/;

// {spec.codename}: generated by hakios_port.py {__version__}.
// No hardware address is invented here.  Every section is filled in from the
// phone's own device tree (adb pull /sys/firmware/fdt) and from what is measured
// on the phone; Documentation/porting.md says where each value comes from.
/ {{
\tname = "{spec.codename}";
\tdescription = "{description}";
\tsoc = "{spec.soc or 'unknown'}";

\t// A feature is listed only after its driver has been seen to work on this
\t// phone.  Empty is the correct starting state.
\tfeatures = <>;

\tbacklight {{
\t\ttype = "soft";
\t}};
}};
'''


def _soc_dtsi(spec: DeviceSpec) -> str:
    return f'''/dts-v1/;

// {spec.soc or 'unknown'}: the SoC layer for {spec.display_name}.
// A SoC layer is shared by every phone with that chip, but it must still be
// checked against this phone's own device tree.  When HakiOS already carries the
// same SoC (devices/<other>/soc.dtsi), copy that file here and verify each block
// against the phone's tree; do not retype addresses from a datasheet.
/ {{
\tname = "{spec.soc or 'unknown'}";
\tdescription = "{spec.soc_name or spec.soc or 'unknown'}";
}};
'''


def _readme(spec: DeviceSpec) -> str:
    return f'''# {spec.codename} (`{spec.codename}`)

| | |
| --- | --- |
| Device | {spec.display_name} |
| Models | {", ".join(spec.models) or "unknown"} |
| SoC | {spec.soc_name or "unknown"} (`{spec.soc or "unknown"}`); `soc.dtsi` |
| State | **Not booted.** No run has been observed on this phone. |

Nothing here writes to the phone's storage. The intended entry is
`fastboot boot <temporary image>`; a reboot returns the phone to Android.

## State

"Compiles", "passes the host tests" and "seen working on the phone" are three
different statements. This port has not reached the third.

| What | Feature / boot argument | State |
| --- | --- | --- |
| Boot to the home screen | — | not tested |
| Display | `backlight {{ }}` / `backlight=` | not tested |
| Touch | `touch-*` | not tested |
| Buttons | `buttons-pmic` / `buttons=1` | not tested |
| CPU frequency | `cpufreq-epss` / `cpufreq=1` | not tested |
| GPU | `gpu-a660` / `gpu=1` | not tested |
| Storage (read-only) | `ufs=1` | not tested |
| Sound, camera, Wi-Fi, haptics | | not tested |

Run `tools/boards.py status {spec.codename}` in a kernel checkout to see what each
feature still needs.

## What a boot needs besides this package

1. A UEFI (or U-Boot) port for this phone, built from its own firmware.
2. The `loader {{ }}` framebuffer base, measured on the phone.
3. A bootloader that implements `fastboot boot`.
4. The firmware files taken from this phone.

If any of these is missing, the port cannot boot and this README must say so
rather than imply otherwise.

## Where the values come from

For each section of `board.dts`: the node of the phone's Android device tree, the
vendor kernel file, Linux's driver tables, or what was measured on the phone. The
device tree itself is never committed.
'''


def _building(spec: DeviceSpec) -> str:
    return f'''# Building this phone

In a checkout of the HakiOS kernel repository:

```sh
tools/device.py add --from <this directory>      # bring the package in
tools/boards.py check                            # validate it
tools/boards.py status {spec.codename}            # what can be turned on next
make kernel                                      # the kernel
LOADER_CFLAGS=-DHAKIOS_NO_PERSISTENT_LOG=1 make loader   # the RAM-only loader
```

The `LOADER_CFLAGS` define is not optional for this project: upstream's loader
writes its log to a partition named `logdump` after every run. The define removes
that write and keeps the log in RAM for `fastboot get_staged`.

The image is built by `tools/image.py` / `arch/arm64/boot/mkboot.py` once the
phone's `uefi {{ }}` section and its UEFI build exist.
'''


GENERATED = {
    "board.dts": _board_dts,
    "soc.dtsi": _soc_dtsi,
    "README.md": _readme,
    "BUILDING.md": _building,
}


def load_manifest(port: Path) -> dict:
    path = Path(port) / MANIFEST
    if not path.is_file():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def save_manifest(port: Path, manifest: dict) -> None:
    path = Path(port) / MANIFEST
    path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")


def generate(spec: DeviceSpec, ports_dir: Path, *, force: bool = False) -> PortResult:
    """Create or top up ``devices/<codename>`` without clobbering edits."""

    port = Path(ports_dir) / spec.codename
    result = PortResult(port=port)
    port.mkdir(parents=True, exist_ok=True)
    manifest = load_manifest(port)

    for name, render in GENERATED.items():
        target = port / name
        content = render(spec).encode("utf-8")
        digest = sha256_bytes(content)
        if not target.exists():
            target.write_bytes(content)
            manifest[name] = digest
            result.created.append(name)
            continue
        existing = sha256_path(target)
        if existing == digest:
            manifest[name] = digest
            result.unchanged.append(name)
            continue
        if manifest.get(name) == existing:
            # This file is the one a previous run wrote, but this version of the
            # tool would generate different bytes.  Do NOT overwrite it just
            # because the template changed: a phone-specific file (a full
            # soc.dtsi, a measured board.dts) is worth more than a template.
            # A person can opt in with --force.
            result.skipped_modified.append(name + " (tool template changed; kept existing)")
            continue
        if force:
            target.write_bytes(content)
            manifest[name] = digest
            result.created.append(name + " (forced)")
            continue
        result.skipped_modified.append(name)

    save_manifest(port, manifest)
    result.issues.extend(validate(spec, port))
    return result


def validate(spec: DeviceSpec, port: Path) -> list[str]:
    """Structural checks that do not need the kernel checkout."""

    port = Path(port)
    issues: list[str] = []

    board = port / "board.dts"
    if not board.is_file():
        return [f"{board} is missing"]
    text = board.read_text(encoding="utf-8", errors="replace")

    match = re.search(r'^\s*name\s*=\s*"([^"]+)"', text, re.MULTILINE)
    if not match:
        issues.append("board.dts has no name")
    elif match.group(1) != spec.codename:
        issues.append(f"board.dts names {match.group(1)!r}, expected {spec.codename!r}")

    if not re.search(r"^\s*soc\s*=\s*\"", text, re.MULTILINE):
        issues.append("board.dts has no soc")

    soc = port / "soc.dtsi"
    if not soc.is_file():
        issues.append("soc.dtsi is missing")

    # A loader section is required for the loader to identify the board.  Its
    # absence is not an error in a new port, but it must be stated.
    if "loader" not in text:
        issues.append(
            "board.dts has no loader { } section: the loader cannot identify this board "
            "until fb-base is measured on the phone (expected for an unported device)"
        )

    for marker in ("TODO", "FIXME", "0xDEAD", "0xdead"):
        if marker in text:
            issues.append(f"board.dts still contains {marker}")

    return issues


def status(spec: DeviceSpec, port: Path) -> str:
    issues = validate(spec, port)
    lines = [f"{spec.codename}: {spec.display_name} ({spec.soc or 'unknown SoC'})"]
    if not issues:
        lines.append("  structural checks: ok")
    else:
        lines.append("  structural checks:")
        for issue in issues:
            lines.append(f"    - {issue}")
    return "\n".join(lines)
